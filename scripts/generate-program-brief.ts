/**
 * Builds PROGRAM_BRIEF.md: the single document the owner pastes to an LLM to
 * get a new training block written in the app's paste format.
 *
 * It stitches together, in order:
 *   1. the prompt (kept here so it is versioned with the code),
 *   2. the programming rules, copied verbatim from TRAINING_SYSTEM.md
 *      sections 10 to 21 (the weekly program sections are skipped on purpose
 *      so the LLM is not anchored on the old week),
 *   3. PROGRAM_FORMAT.md in full, which carries the exercise library.
 *
 * Run after any change to PROGRAM_FORMAT.md (so after
 * generate-program-format-library.ts), TRAINING_SYSTEM.md, or the prompt:
 *   npx tsx scripts/generate-program-brief.ts
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(__dirname, '..');
const OUTPUT_PATH = resolve(ROOT, 'PROGRAM_BRIEF.md');
const TRAINING_SYSTEM_PATH = resolve(ROOT, 'TRAINING_SYSTEM.md');
const PROGRAM_FORMAT_PATH = resolve(ROOT, 'PROGRAM_FORMAT.md');

const RULES_FIRST_HEADING = '## 10. ';
const RULES_STOP_HEADING = '## 22. ';

const PROMPT = `# Program brief

> Generated by \`scripts/generate-program-brief.ts\`. Do not edit by hand. Paste this whole file to an LLM together with one message that gives the block details (see "What I will tell you in my message").

## Your task

You are writing my next training block as a program file for my training app. Read this whole document first. Part 1 is who I am and what the block must achieve. Part 2 is the programming rules; follow them exactly and do not change any rule. Part 3 is the exact text format the app can read, plus the list of exercise names the app knows.

## What I will tell you in my message

My message alongside this document gives the block details: how many training days, which weekdays, how many weeks, time available per session, equipment limits, any current pain or injury, and what felt too hard or too easy in the last block. If my message leaves any of these out, assume five gym days, Monday to Friday, 60 minutes each, a full commercial gym, and no current pain.

## How to answer

1. First, a rationale of at most 200 words: how the week is split, the weekly set count per major muscle group, where speed, power, calisthenics, abs, and mobility live, and how this block differs from the last one.
2. Then the whole program as ONE fenced code block in the Part 3 paste format. Nothing outside the code block belongs to the program.
3. After the code block, a short list titled "Not in the library" naming any exercise you used that does not appear in the Part 3 library list, or "None" if every name matched.

## Hard requirements for the program

- Use exercise names from the Part 3 library spelled exactly as written. Prefer a library name over a near synonym. Use a name outside the library only when nothing in it fits.
- Every section needs a type from the allowed list in Part 3.
- Every training day has a "Target duration" line.
- Monday, Wednesday, and Thursday get the line "+ Ultimate practice later". Those sessions must leave me fresh enough to play that evening.
- Nothing on Sunday. Any weekday I do not train is simply left out.
- No running, sprinting, accelerations, treadmill, or walking lines. Running happens outside the gym and outside this program.
- Supersets use the superset clause from Part 3, both lines next to each other in the same section, equal set counts, rest guidance on the second line of the pair.
- Rest guidance on every strength line, using the rest categories from Part 3.
- Rep ranges, not fixed reps, for hypertrophy work, so double progression applies.
- Power and calisthenics skill work comes before heavy strength work in a session.
- Abs are programmed with sets, reps or holds, and progression, like any other muscle group.
- Mobility and adductor work are placed inside sessions, not listed as a separate day of homework.

# Part 1: The athlete and the goal

I am a recreational Ultimate frisbee player. I lift in the morning. Ultimate practice is on Monday, Wednesday, and Thursday evenings and counts as significant athletic workload, including sprinting, cutting, and repeated sprint conditioning. The program must not assume more conditioning is always better.

The block's philosophy, in priority order: build muscle, keep my speed, become stronger relative to my bodyweight, move well. Muscle gain is the primary adaptation goal. Athleticism must be maintained and preferably improved, never sacrificed for size. Calisthenics (planche and L-sit progressions, handstand work) is a real training objective, not a side activity. Abs are a high-priority physique goal. HYROX is a future phase; do not program for it now.

Where this block fits: the app tracks every set against the rep range, so the next session shows previous performance and I progress by double progression. Write the block so that progression is visible week to week without you having to write separate weeks: one week template is what the app stores and I repeat it for the length of the block.

`;

function readNormalized(path: string): string {
  return readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
}

function extractRules(trainingSystem: string): string {
  const lines = trainingSystem.split('\n');
  const start = lines.findIndex((line) => line.startsWith(RULES_FIRST_HEADING));
  const stop = lines.findIndex((line) => line.startsWith(RULES_STOP_HEADING));
  if (start === -1 || stop === -1 || stop <= start) {
    throw new Error(
      `TRAINING_SYSTEM.md no longer has "${RULES_FIRST_HEADING}" before "${RULES_STOP_HEADING}"; update generate-program-brief.ts`
    );
  }
  return lines.slice(start, stop).join('\n').trimEnd();
}

function extractFormat(programFormat: string): string {
  const firstLineBreak = programFormat.indexOf('\n');
  const firstLine = programFormat.slice(0, firstLineBreak);
  if (firstLine !== '# PROGRAM_FORMAT.md') {
    throw new Error(`PROGRAM_FORMAT.md no longer starts with its title line; update generate-program-brief.ts`);
  }
  return programFormat.slice(firstLineBreak + 1).trim();
}

function main(): void {
  const rules = extractRules(readNormalized(TRAINING_SYSTEM_PATH));
  const format = extractFormat(readNormalized(PROGRAM_FORMAT_PATH));

  const output = [
    PROMPT.trimEnd(),
    '',
    '# Part 2: Programming rules (follow exactly)',
    '',
    'Copied from the training system document. Section numbers are kept from the source.',
    '',
    rules,
    '',
    '# Part 3: The paste format and the exercise library',
    '',
    'This is the format the app reads. "You" below means the person pasting; the output you write must follow it exactly.',
    '',
    format,
    '',
  ].join('\n');

  writeFileSync(OUTPUT_PATH, output);
  console.log(`Wrote ${OUTPUT_PATH} (${output.split('\n').length} lines)`);
}

main();
